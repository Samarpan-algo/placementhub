-- V1: initial PlacementHub schema.
-- Conventions:
--   * IDs are BIGINT identity columns; timestamps are TIMESTAMPTZ (app runs in UTC).
--   * Enums are VARCHAR + CHECK (maps to JPA @Enumerated(EnumType.STRING)).
--   * Foreign keys are ON DELETE RESTRICT (we close/deactivate, not delete),
--     except drive_branches, which are pure child rows of a drive (CASCADE).
--   * Postgres does not index foreign keys automatically; every FK column is
--     covered by its own index or by the leading column of a PK/UNIQUE index.
--   * updated_at columns are maintained by the application (JPA), not triggers.

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_users_email      UNIQUE (email),
    CONSTRAINT ck_users_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_users_role       CHECK (role IN ('STUDENT', 'TPO_ADMIN'))
);

-- ---------------------------------------------------------------------------
-- student_profiles (1:1 with a STUDENT user)
-- ---------------------------------------------------------------------------
CREATE TABLE student_profiles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    full_name       VARCHAR(100) NOT NULL,
    roll_no         VARCHAR(30)  NOT NULL,
    branch          VARCHAR(10)  NOT NULL,
    graduation_year SMALLINT     NOT NULL,
    cgpa            NUMERIC(4,2) NOT NULL,
    active_backlogs SMALLINT     NOT NULL DEFAULT 0,
    phone           VARCHAR(15),
    resume_url      TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_student_profiles_user_id  UNIQUE (user_id),
    CONSTRAINT uq_student_profiles_roll_no  UNIQUE (roll_no),
    CONSTRAINT fk_student_profiles_user     FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_student_profiles_branch   CHECK (branch IN ('CSE', 'IT', 'ECE', 'EEE', 'ME', 'CE')),
    CONSTRAINT ck_student_profiles_grad_year CHECK (graduation_year BETWEEN 2000 AND 2100),
    CONSTRAINT ck_student_profiles_cgpa     CHECK (cgpa BETWEEN 0 AND 10),
    CONSTRAINT ck_student_profiles_backlogs CHECK (active_backlogs >= 0)
);
-- user_id is indexed by its UNIQUE constraint.

-- ---------------------------------------------------------------------------
-- companies
-- ---------------------------------------------------------------------------
CREATE TABLE companies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    website     VARCHAR(255),
    description TEXT,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_companies_name UNIQUE (name)
);

-- ---------------------------------------------------------------------------
-- drives (a company's hiring drive, with eligibility criteria)
-- ---------------------------------------------------------------------------
CREATE TABLE drives (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            BIGINT       NOT NULL,
    role_title            VARCHAR(150) NOT NULL,
    job_type              VARCHAR(20)  NOT NULL,
    ctc_lpa               NUMERIC(6,2) NOT NULL,
    location              VARCHAR(150),
    description           TEXT,
    min_cgpa              NUMERIC(4,2) NOT NULL DEFAULT 0,
    max_backlogs          SMALLINT     NOT NULL DEFAULT 0,
    graduation_year       SMALLINT     NOT NULL,
    registration_deadline TIMESTAMPTZ  NOT NULL,
    drive_date            DATE,
    status                VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    created_by            BIGINT       NOT NULL,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_drives_company      FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_drives_created_by   FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_drives_job_type     CHECK (job_type IN ('FULL_TIME', 'INTERNSHIP')),
    CONSTRAINT ck_drives_ctc          CHECK (ctc_lpa > 0),
    CONSTRAINT ck_drives_min_cgpa     CHECK (min_cgpa BETWEEN 0 AND 10),
    CONSTRAINT ck_drives_max_backlogs CHECK (max_backlogs >= 0),
    CONSTRAINT ck_drives_grad_year    CHECK (graduation_year BETWEEN 2000 AND 2100),
    CONSTRAINT ck_drives_status       CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED', 'COMPLETED'))
);
CREATE INDEX idx_drives_company_id ON drives (company_id);
CREATE INDEX idx_drives_created_by ON drives (created_by);
CREATE INDEX idx_drives_status     ON drives (status);

-- ---------------------------------------------------------------------------
-- drive_branches (which branches may apply to a drive)
-- ---------------------------------------------------------------------------
CREATE TABLE drive_branches (
    drive_id BIGINT      NOT NULL,
    branch   VARCHAR(10) NOT NULL,

    CONSTRAINT pk_drive_branches        PRIMARY KEY (drive_id, branch),
    CONSTRAINT fk_drive_branches_drive  FOREIGN KEY (drive_id) REFERENCES drives (id) ON DELETE CASCADE,
    CONSTRAINT ck_drive_branches_branch CHECK (branch IN ('CSE', 'IT', 'ECE', 'EEE', 'ME', 'CE'))
);
-- drive_id is indexed as the leading column of the primary key.

-- ---------------------------------------------------------------------------
-- applications (one per student per drive)
-- ---------------------------------------------------------------------------
-- REJECTED   = rejected by the company in a round.
-- INELIGIBLE = no longer meets criteria after an admin edited the drive;
--              status_reason holds the human-readable explanation.
-- WITHDRAWN  = final: the UNIQUE constraint prevents re-applying.
CREATE TABLE applications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_id      BIGINT       NOT NULL,
    student_id    BIGINT       NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'APPLIED',
    status_reason VARCHAR(300),
    applied_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_applications_drive_student UNIQUE (drive_id, student_id),
    CONSTRAINT fk_applications_drive   FOREIGN KEY (drive_id)   REFERENCES drives (id)           ON DELETE RESTRICT,
    CONSTRAINT fk_applications_student FOREIGN KEY (student_id) REFERENCES student_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT ck_applications_status  CHECK (status IN ('APPLIED', 'SHORTLISTED', 'REJECTED', 'SELECTED', 'WITHDRAWN', 'INELIGIBLE'))
);
-- drive_id is indexed as the leading column of uq_applications_drive_student.
CREATE INDEX idx_applications_student_id ON applications (student_id);
CREATE INDEX idx_applications_status     ON applications (status);

-- ---------------------------------------------------------------------------
-- drive_rounds
-- ---------------------------------------------------------------------------
CREATE TABLE drive_rounds (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_id     BIGINT       NOT NULL,
    round_no     SMALLINT     NOT NULL,
    name         VARCHAR(100) NOT NULL,
    scheduled_at TIMESTAMPTZ,

    CONSTRAINT uq_drive_rounds_drive_round_no UNIQUE (drive_id, round_no),
    CONSTRAINT fk_drive_rounds_drive          FOREIGN KEY (drive_id) REFERENCES drives (id) ON DELETE RESTRICT,
    CONSTRAINT ck_drive_rounds_round_no       CHECK (round_no > 0)
);
-- drive_id is indexed as the leading column of uq_drive_rounds_drive_round_no.

-- ---------------------------------------------------------------------------
-- round_results (one result per application per round)
-- ---------------------------------------------------------------------------
-- The service must ensure the application belongs to the same drive as the round.
CREATE TABLE round_results (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id       BIGINT       NOT NULL,
    application_id BIGINT       NOT NULL,
    result         VARCHAR(20)  NOT NULL,
    remarks        VARCHAR(500),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_round_results_round_application UNIQUE (round_id, application_id),
    CONSTRAINT fk_round_results_round       FOREIGN KEY (round_id)       REFERENCES drive_rounds (id) ON DELETE RESTRICT,
    CONSTRAINT fk_round_results_application FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE RESTRICT,
    CONSTRAINT ck_round_results_result      CHECK (result IN ('CLEARED', 'NOT_CLEARED', 'ABSENT'))
);
-- round_id is indexed as the leading column of uq_round_results_round_application.
CREATE INDEX idx_round_results_application_id ON round_results (application_id);

-- ---------------------------------------------------------------------------
-- placement_policies (exactly one row per policy type)
-- ---------------------------------------------------------------------------
CREATE TABLE placement_policies (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type              VARCHAR(20)  NOT NULL,
    ctc_threshold_lpa NUMERIC(6,2),
    max_offers        SMALLINT,
    active            BOOLEAN      NOT NULL DEFAULT FALSE,
    updated_by        BIGINT,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_placement_policies_type        UNIQUE (type),
    CONSTRAINT fk_placement_policies_updated_by  FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_placement_policies_type        CHECK (type IN ('ONE_OFFER', 'DREAM_OFFER', 'MAX_OFFERS')),
    CONSTRAINT ck_placement_policies_threshold   CHECK (ctc_threshold_lpa > 0),
    CONSTRAINT ck_placement_policies_max_offers  CHECK (max_offers >= 1),
    CONSTRAINT ck_placement_policies_dream_needs_threshold CHECK (type <> 'DREAM_OFFER' OR ctc_threshold_lpa IS NOT NULL),
    CONSTRAINT ck_placement_policies_max_needs_limit       CHECK (type <> 'MAX_OFFERS' OR max_offers IS NOT NULL)
);
CREATE INDEX idx_placement_policies_updated_by ON placement_policies (updated_by);

-- ---------------------------------------------------------------------------
-- audit_logs (append-only history; entity_id is polymorphic, so no FK)
-- ---------------------------------------------------------------------------
CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(30) NOT NULL,
    entity_id   BIGINT      NOT NULL,
    action      VARCHAR(30) NOT NULL,
    old_value   JSONB,
    new_value   JSONB,
    actor_id    BIGINT,                -- NULL = system action
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_audit_logs_actor      FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_audit_logs_entity_type CHECK (entity_type IN ('DRIVE', 'APPLICATION')),
    CONSTRAINT ck_audit_logs_action      CHECK (action IN ('CRITERIA_CHANGED', 'STATUS_CHANGED'))
);
CREATE INDEX idx_audit_logs_entity     ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_logs_actor_id   ON audit_logs (actor_id);
CREATE INDEX idx_audit_logs_created_at ON audit_logs (created_at);
